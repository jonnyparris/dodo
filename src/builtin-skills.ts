export function listBuiltinSkills(): Skill[] {
  return BUILTIN_SKILLS.map((entry) => ({
    name: entry.name,
    description: entry.description,
    body: entry.body,
    source: "builtin" as const,
    location: `builtin://${entry.name}`,
    assetPaths: [],
    enabled: true,
  }));
}
